const isLocalizedText = (value) => (
  value
  && typeof value === 'object'
  && Object.prototype.hasOwnProperty.call(value, 'zh')
  && Object.prototype.hasOwnProperty.call(value, 'en')
);

const selectLanguage = (value, language, path = []) => {
  if (isLocalizedText(value)) {
    if (language === 'ja') return japaneseTranslations[path.join('.')]?.ja ?? value.en;
    return value[language];
  }

  return Object.fromEntries(
    Object.entries(value).map(([key, child]) => [
      key,
      selectLanguage(child, language, [...path, key]),
    ])
  );
};

export const resources = {
  zh: { translation: selectLanguage(bilingualConfig, 'zh') },
  en: { translation: selectLanguage(bilingualConfig, 'en') },
  ja: { translation: selectLanguage(bilingualConfig, 'ja') },
};

export default resources;
