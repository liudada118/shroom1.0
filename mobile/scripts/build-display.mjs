import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const clientRoot = path.resolve(mobileRoot, '../client');
const clientRequire = createRequire(path.join(clientRoot, 'package.json'));

/** 构建既有渲染器并内联为离线 HTML；临时构建不覆盖桌面 build。 */
export async function buildOfflineDisplay() {
  const temporaryRoot = await fs.mkdtemp(path.join(os.tmpdir(), 'shroom-ipad-display-'));
  try {
    const vitePackage = clientRequire.resolve('vite/package.json');
    const { build } = await import(pathToFileURL(path.join(path.dirname(vitePackage), 'dist/node/index.js')).href);
    await build({ configFile: path.join(clientRoot, 'vite.mobile.config.js'), build: { outDir: temporaryRoot } });
    const script = await fs.readFile(path.join(temporaryRoot, 'display.js'), 'utf8');
    const filenames = await fs.readdir(temporaryRoot);
    const cssFiles = filenames.filter((name) => name.endsWith('.css'));
    const css = (await Promise.all(cssFiles.map((name) => fs.readFile(path.join(temporaryRoot, name), 'utf8')))).join('\n');
    if (!script || !css || filenames.some((name) => !name.endsWith('.js') && !name.endsWith('.css'))) {
      throw new Error('移动显示构建必须仅包含可内联的 JS/CSS，请检查外部资源。');
    }
    const template = await fs.readFile(path.join(clientRoot, 'mobile.html'), 'utf8');
    const policy = `<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data: blob:; font-src data:; connect-src 'none';">`;
    const html = template.replace('</head>', `${policy}<style>${css.replace(/<\/style/gi, '<\\/style')}</style></head>`)
      .replace(/<script\b[^>]*src="\.\/src\/mobile\/main\.jsx"[^>]*><\/script>/,
        () => `<script>${script.replace(/<\/script/gi, '<\\/script')}</script>`);
    if (html.includes('src="./src/mobile/main.jsx"')) throw new Error('离线页面没有替换开发入口。');
    const destination = path.join(mobileRoot, 'generated');
    await fs.mkdir(destination, { recursive: true });
    await fs.writeFile(path.join(destination, 'display.ts'), `// Generated by build-display.mjs; do not edit.\nexport const displayHtml = ${JSON.stringify(html)};\n`, 'utf8');
    console.log(`Offline iPad display ready: ${Math.round(Buffer.byteLength(html) / 1024)} KiB`);
    return html;
  } finally {
    const resolved = path.resolve(temporaryRoot);
    if (path.dirname(resolved) !== path.resolve(os.tmpdir()) || !path.basename(resolved).startsWith('shroom-ipad-display-')) {
      throw new Error('拒绝清理非本次构建的临时目录。');
    }
    await fs.rm(resolved, { recursive: true, force: true });
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildOfflineDisplay();
