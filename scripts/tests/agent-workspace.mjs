  /** 用 DOM 文件事件测试粘贴，不读取或改写用户操作系统剪贴板。 */
  async function paste(files = [], text = '') {
    return page.getByLabel('任务内容').evaluate((element, payload) => {
      const data = new DataTransfer();
      for (const file of payload.files) data.items.add(new File([Uint8Array.from(atob(file.base64), (char) => char.charCodeAt(0))], file.name, { type: file.type || 'text/plain' }));
      if (payload.text) data.setData('text/plain', payload.text);
      const event = new ClipboardEvent('paste', { clipboardData: data, bubbles: true, cancelable: true });
      element.dispatchEvent(event);
      return event.defaultPrevented;
    }, { files, text });
  }
