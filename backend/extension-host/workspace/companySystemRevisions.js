const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createHash, randomUUID, verify } = require('node:crypto');
const { loadDisplaySystemDirectory } = require('../manifest/displaySystemConfigLoader');
const { installManifestPackage, installNativePackage } = require('./systemPackageService');
const PUBLIC_KEY = fs.readFileSync(path.join(__dirname, 'systemPackagePublicKey.pem'), 'utf8');
const SAFE_ID = /^[A-Za-z0-9][A-Za-z0-9._-]{0,79}$/;

/** Verify the publisher's detached signature over a package digest. */
function verifyDigest(sha256, signature) {
  return verify(null, Buffer.from(sha256, 'hex'), PUBLIC_KEY, Buffer.from(signature, 'base64'));
}

/** Recompute the signed package digest before trusting a published release or saved draft source. */
function hasPackageIntegrity(release) {
  if (!release?.package || typeof release.package !== 'object' || Array.isArray(release.package)) return false;
  const { sha256, ...payload } = release.package;
  return sha256 === release.sha256
    && createHash('sha256').update(JSON.stringify(payload)).digest('hex') === sha256;
}

/** Return a stable revision error for the local API and its UI. */
function revisionError(code, message) { return Object.assign(new Error(message), { code }); }

/** Hash a package after editing its own identity, preserving the installation checksum contract. */
function sealPackage(input) {
  const { sha256, ...payload } = input;
  return { ...payload, sha256: createHash('sha256').update(JSON.stringify(payload)).digest('hex') };
}

/** Verify the server's immutable published artifact before copying it into a local editable workspace. */
function verifyPublishedRelease(release) {
  return release?.package?.systemId === release.systemId && hasPackageIntegrity(release)
    && /^[a-f0-9]{64}$/.test(release.sha256 || '') && typeof release.signature === 'string'
    && verifyDigest(release.sha256, release.signature);
}

/** Create and export isolated revisions while retaining the published system and its data untouched. */
function createCompanySystemRevisions({ root, workspace, builtinTemplates, getById, reload, exportPackage,
  readBindings = () => null, updateBindings = () => null, listPackages = () => [],
  verifyRelease = verifyPublishedRelease }) {
  const metadataRoot = path.join(root, 'company-system-revisions');

  /** Read only metadata generated by this service; never use a request value as an arbitrary file path. */
  function read(draftId) {
    if (!SAFE_ID.test(draftId || '') || !draftId.startsWith('revision_')) return null;
    const filename = path.join(metadataRoot, `${draftId}.json`);
    try {
      const value = JSON.parse(fs.readFileSync(filename, 'utf8'));
      return value.draftId === draftId && SAFE_ID.test(value.targetSystemId || '') ? value : null;
    } catch { return null; }
  }

  /** Recheck the complete signed source package and its link to this draft's stable target. */
  function trustedSource(record) {
    try {
      const release = JSON.parse(fs.readFileSync(path.join(metadataRoot, `${record.draftId}.source.json`), 'utf8'));
      if (release.systemId !== record.targetSystemId || release.version !== record.baseVersion
        || release.sha256 !== record.baseSha256 || release.signature !== record.baseSignature
        || release.package?.kind !== record.kind || !hasPackageIntegrity(release) || !verifyRelease(release)
        || (record.kind === 'native-template' && release.package.template?.sourceType !== record.sourceType)) return null;
      return release;
    } catch { return null; }
  }

  /** List persistent local drafts independently of the current Agent conversation or customer key. */
  function list() {
    if (!fs.existsSync(metadataRoot)) return [];
    return fs.readdirSync(metadataRoot).filter((name) => /^revision_[a-f0-9]+\.json$/.test(name))
      .map((name) => read(name.slice(0, -5))).filter((item) => item && isDraftId(item.draftId))
      .map((item) => ({ draftId: item.draftId, targetSystemId: item.targetSystemId, baseVersion: item.baseVersion,
        kind: item.kind, name: item.name, available: Boolean(getById(item.draftId)) }));
  }

  /** Create a local editor identity from the exact published package; existing classifiers need a separate ID migration. */
  function create(release) {
    if (!SAFE_ID.test(release?.systemId || '') || !Number.isSafeInteger(release.version) || release.version < 1
      || !verifyRelease(release) || !['manifest', 'native-template'].includes(release.package?.kind)) {
      throw revisionError('SYSTEM_RELEASE_INVALID', '已发布系统的版本、签名或系统包无效，请刷新公司系统库');
    }
    const input = release.package;
    if ((input.algorithms || []).length || (input.bindings?.algorithms || []).some((item) => item.packageId?.startsWith('user-'))
      || (input.template?.configuration?.algorithms || []).some((item) => item.packageId?.startsWith('user-'))) {
      throw revisionError('SYSTEM_REVISION_ALGORITHMS_UNSUPPORTED', '该版本包含用户分类算法；当前草稿无法安全迁移算法身份，暂不能从它创建修订草稿');
    }
    const existing = list().find((item) => item.targetSystemId === release.systemId && item.baseVersion === release.version);
    if (existing?.available) return { ...existing, reused: true };
    if (existing) throw Object.assign(revisionError('SYSTEM_REVISION_DRAFT_UNAVAILABLE',
      `此系统已有基于版本 #${release.version} 的本机草稿，但草稿配置不可读取；请先修复该草稿`), { httpStatus: 409 });
    const draftId = `revision_${randomUUID().replaceAll('-', '').slice(0, 20)}`;
    const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'shroom-company-revision-'));
    let created = false;
    try {
      let metadata;
      if (input.kind === 'manifest') {
        const installed = installManifestPackage(input, { managedRoot: temporary, listPackages });
        const loaded = loadDisplaySystemDirectory(installed.directory, { validateFiles: true });
        if (!loaded.ok) throw revisionError('SYSTEM_RELEASE_INVALID', loaded.errors?.[0] || '已发布系统配置无法读取');
        const baseManifest = JSON.parse(fs.readFileSync(path.join(installed.directory, 'display-system.json'), 'utf8'));
        const sensors = baseManifest.sensors || (baseManifest.sensor ? [baseManifest.sensor] : []);
        const result = workspace.duplicate(loaded.config, { id: draftId, name: baseManifest.name,
          independentSensorTypes: true });
        created = true;
        for (const name of ['package-info.json', 'package-bindings.json']) {
          fs.rmSync(path.join(result.directory, name), { force: true });
        }
        metadata = { kind: 'manifest', name: baseManifest.name, baseMetadata: baseManifest.metadata || {},
          sensors: sensors.map((sensor) => ({ id: sensor.id || null, type: sensor.type,
            outputChannel: sensor.outputChannel || null, matrix: sensor.matrix })),
          baseBindings: input.bindings || { algorithms: [], charts: [] } };
      } else {
        installNativePackage(input, { managedRoot: temporary, listPackages });
        builtinTemplates.create({ id: draftId, name: input.template.name, sourceType: input.template.sourceType,
          configuration: input.template.configuration });
        created = true;
        metadata = { kind: 'native-template', name: input.template.name, sourceType: input.template.sourceType,
          baseConfiguration: input.template.configuration };
      }
      const record = { ...metadata, draftId, targetSystemId: release.systemId, baseVersion: release.version,
        baseSha256: release.sha256, baseSignature: release.signature, createdAt: new Date().toISOString() };
      reload();
      if (record.kind === 'manifest' && input.bindings) {
        const current = readBindings(draftId);
        updateBindings(draftId, { expectedRevision: current.revision, configuration: input.bindings });
      }
      const baseline = projectExport(draftId, record);
      record.baselineSha256 = baseline.sha256;
      record.baselineFileHashes = record.kind === 'manifest'
        ? Object.fromEntries(baseline.files.map((file) => [file.path, file.sha256])) : {};
      fs.mkdirSync(metadataRoot, { recursive: true });
      fs.writeFileSync(path.join(metadataRoot, `${draftId}.source.json`), JSON.stringify(release), { flag: 'wx' });
      fs.writeFileSync(path.join(metadataRoot, `${draftId}.json`), JSON.stringify(record, null, 2), { flag: 'wx' });
      return { draftId, targetSystemId: record.targetSystemId, baseVersion: record.baseVersion,
        kind: record.kind, name: record.name, available: true };
    } catch (error) {
      if (created) {
        if (input.kind === 'manifest') fs.rmSync(path.join(workspace.writableRoot, draftId), { recursive: true, force: true });
        else fs.rmSync(path.join(builtinTemplates.userRoot, `${draftId}.json`), { force: true });
        fs.rmSync(path.join(metadataRoot, `${draftId}.json`), { force: true });
        fs.rmSync(path.join(metadataRoot, `${draftId}.source.json`), { force: true });
        reload();
      }
      throw error;
    } finally { fs.rmSync(temporary, { recursive: true, force: true }); }
  }

  /** Preserve the published sensor identity while allowing editable display, mapping and algorithm contents. */
  function restoreManifestIdentity(exported, record) {
    const next = structuredClone(exported);
    const file = next.files.find((item) => item.path === 'display-system.json');
    if (!file) throw revisionError('SYSTEM_REVISION_INVALID', '草稿缺少展示系统声明');
    const manifest = JSON.parse(Buffer.from(file.contentBase64, 'base64').toString('utf8'));
    const sensors = manifest.sensors || (manifest.sensor ? [manifest.sensor] : []);
    if (sensors.length !== record.sensors.length) throw revisionError('SYSTEM_REVISION_INPUT_CHANGED', '修订草稿更改了传感器数量；当前版本更新要求保留原输入身份');
    sensors.forEach((sensor, index) => {
      const base = record.sensors[index];
      const expectedDraftType = index ? `${record.draftId}-${index + 1}` : record.draftId;
      if ((sensor.id || null) !== base.id || sensor.type !== expectedDraftType
        || (sensor.outputChannel || null) !== base.outputChannel
        || sensor.matrix?.rows !== base.matrix?.rows || sensor.matrix?.cols !== base.matrix?.cols) {
        throw revisionError('SYSTEM_REVISION_INPUT_CHANGED', '修订草稿更改了传感器 ID、通道或矩阵尺寸；请恢复后提交，破坏输入契约需另建系统');
      }
      sensor.type = base.type;
    });
    manifest.id = record.targetSystemId;
    manifest.metadata = record.baseMetadata;
    if (manifest.sensor) manifest.sensor.type = record.sensors[0].type;
    const data = Buffer.from(JSON.stringify(manifest, null, 2) + '\n');
    Object.assign(file, { size: data.length, sha256: createHash('sha256').update(data).digest('hex'), contentBase64: data.toString('base64') });
    next.systemId = record.targetSystemId;
    next.algorithms = next.algorithms.map((item) => ({ ...item, systemId: record.targetSystemId }));
    return sealPackage(next);
  }

  /** Transform an editable draft into the original published identity without writing it to disk. */
  function projectExport(draftId, record) {
    const exported = exportPackage(draftId);
    let input;
    if (record.kind === 'manifest') input = restoreManifestIdentity(exported, record);
    else {
      if (exported.kind !== 'native-template' || exported.template.sourceType !== record.sourceType) {
        throw revisionError('SYSTEM_REVISION_INPUT_CHANGED', '原生模板来源已变化，不能覆盖已发布系统');
      }
      input = sealPackage({ ...exported, systemId: record.targetSystemId,
        template: { ...exported.template, id: record.targetSystemId },
        algorithms: exported.algorithms.map((item) => ({ ...item, systemId: record.targetSystemId })) });
    }
    if (input.systemId !== record.targetSystemId) throw revisionError('SYSTEM_REVISION_INVALID', '修订包系统 ID 不一致');
    return input;
  }

  /** Re-export the current editable draft against its fixed published baseline for preview or submission. */
  function exportRevision(draftId) {
    const record = read(draftId);
    if (!record || !isDraftId(draftId)) {
      throw revisionError('SYSTEM_REVISION_NOT_FOUND', '修订草稿不存在、来源签名无效或已不可编辑');
    }
    if (!getById(draftId)?.editable) throw revisionError('SYSTEM_REVISION_INPUT_CHANGED', '修订草稿配置无效，请检查传感器尺寸、线序和文件引用');
    const input = projectExport(draftId, record);
    return { package: input, baseVersion: record.baseVersion };
  }

  /** Summarize actual exported changes and reject an accidental no-op submission. */
  function inspect(draftId) {
    const record = read(draftId);
    if (!record) throw revisionError('SYSTEM_REVISION_NOT_FOUND', '修订草稿不存在');
    const { package: input } = exportRevision(draftId);
    const changedFiles = record.kind === 'manifest'
      ? input.files.filter((file) => record.baselineFileHashes?.[file.path] !== file.sha256).map((file) => file.path)
      : [];
    const changedBindings = record.kind === 'manifest' && JSON.stringify(input.bindings || { algorithms: [], charts: [] }) !== JSON.stringify(record.baseBindings);
    const changedConfiguration = record.kind === 'native-template'
      && (input.template.name !== record.name || JSON.stringify(input.template.configuration) !== JSON.stringify(record.baseConfiguration));
    return { draftId, targetSystemId: record.targetSystemId, baseVersion: record.baseVersion,
      packageSha256: input.sha256,
      kind: record.kind, name: input.kind === 'manifest' ? JSON.parse(Buffer.from(input.files.find((file) => file.path === 'display-system.json').contentBase64, 'base64').toString('utf8')).name : input.template.name,
      changedFiles, changedBindings: Boolean(changedBindings), changedConfiguration: Boolean(changedConfiguration), changedAlgorithms: input.algorithms.length > 0,
      hasChanges: input.sha256 !== record.baselineSha256 };
  }

  /** Identify only drafts derived from a previously verified signed release, even after staff login expires. */
  function isDraftId(draftId) {
    const record = read(draftId);
    if (!record || !trustedSource(record)) return false;
    try {
      if (record.kind === 'native-template') {
        const draft = JSON.parse(fs.readFileSync(path.join(builtinTemplates.userRoot, `${draftId}.json`), 'utf8'));
        return draft.id === draftId && draft.sourceType === record.sourceType && !draft.managedPackage;
      }
      const draft = JSON.parse(fs.readFileSync(path.join(workspace.writableRoot, draftId, 'display-system.json'), 'utf8'));
      return draft.id === draftId;
    } catch { return false; }
  }

  return { create, list, inspect, exportRevision, isDraftId };
}

module.exports = { createCompanySystemRevisions, verifyPublishedRelease };
